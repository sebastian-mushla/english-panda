export function t(key, vars) {
  // для изучаемого языка может быть свой вариант текста: ключ@cz (правила чешской грамматики и т. п.)
  const k2 = key + '@' + TARGET;
  let s = S[state.lang]?.[k2] ?? S.ru[k2] ?? S[state.lang]?.[key] ?? S.ru[key] ?? key;
  if (s.includes('{t')) s = s.replace('{tl}', LANG_ADV[TARGET][state.lang]).replace('{tln}', LANG_NAME[TARGET][state.lang]);
  if (s.includes('{off}')) s = s.replace('{off}', OFFICIAL[TARGET]);
  if (vars) for (const k in vars) s = s.replaceAll('{' + k + '}', vars[k]);
  return s;
}

