  const m10 = n % 10, m100 = n % 100;
  if (state.lang === 'uk') return n + ' ' + (m10 === 1 && m100 !== 11 ? 'слово' : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? 'слова' : 'слів');
